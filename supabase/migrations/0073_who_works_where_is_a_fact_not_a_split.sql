-- Πού εργάζεται ο καθένας είναι στοιχείο, όχι μοίρασμα χρημάτων.
--
-- Ο Owner: «θα πρέπει να γράφουμε πού εργάζεται ο καθένας, σε ποιο
-- κατάστημα, καφέ ή πρακτορείο, ή και διττό ρόλο».
--
-- Τα δύο πρώτα υπήρχαν ήδη: το payroll_records έχει store_id και unit
-- ('STORE' | 'FNB') από το 0019, και από το «Two businesses were adding up
-- to one number» η μονάδα αποφασίζει σε ποια πλευρά του P&L πέφτει ο
-- μισθός. Αυτό που δεν υπήρχε είναι ο διττός ρόλος.
--
-- Η προφανής υλοποίηση -- ένα ποσοστό ανά άτομο, 40% καφέ και 60%
-- πρακτορείο -- ρωτήθηκε και ΑΠΟΡΡΙΦΘΗΚΕ: «ας το αφήσουμε εντελώς αυτό το
-- ποσοστό, δε μας νοιάζει». Οπότε εδώ δεν μπαίνει κανένας κανόνας
-- επιμερισμού.
--
-- Το dual_role είναι ΜΟΝΟ πληροφορία: ποιος καλύπτει και τα δύο πόστα.
-- Δεν αγγίζει ευρώ. Ο μισθός εξακολουθεί να χρεώνεται ολόκληρος στη
-- μονάδα που επιλέγεται, και το άθροισμα των δύο πλευρών παραμένει ίσο με
-- το σύνολο της μισθοδοσίας -- η αμετάβλητη ιδιότητα που κρατάει τις δύο
-- κερδοφορίες να συμφωνούν με την τελική γραμμή από κάτω τους.
--
-- Αν κάποτε χρειαστεί πραγματικός επιμερισμός, θα είναι ξεχωριστή απόφαση
-- με ξεχωριστή στήλη. Ένα boolean δεν μπορεί να γίνει σιωπηλά ποσοστό.

ALTER TABLE payroll_records
  ADD COLUMN IF NOT EXISTS dual_role BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN payroll_records.dual_role IS
  'Καλύπτει και πρακτορείο και καφέ. Καταγραφή μόνο - ο μισθός χρεώνεται ολόκληρος στο unit.';
