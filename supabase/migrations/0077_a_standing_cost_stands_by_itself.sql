-- Ένα πάγιο στέκει μόνο του.
--
-- Τα πάγια έξοδα είναι, εξ ορισμού, τα ίδια κάθε μήνα: ενοίκιο, ΔΕΗ, ΟΤΕ,
-- ασφάλιστρα. Μέχρι τώρα έπρεπε να πατηθεί «Από προηγούμενο μήνα» σε κάθε
-- κατάστημα, κάθε μήνα - δηλαδή το σύστημα ζητούσε επιβεβαίωση για το
-- πράγμα που ο ίδιος ο όρος «πάγιο» υπόσχεται ότι δεν αλλάζει.
--
-- Ο διακόπτης μπαίνει ΑΝΑ ΚΑΤΑΣΤΗΜΑ, δίπλα στα υπόλοιπα του ίδιου είδους
-- (inspection_mode, collection_summary_mode): ένα Play με δύο πάγια και ένα
-- πρακτορείο με δεκαπέντε δεν θέλουν την ίδια απάντηση.
--
-- Προεπιλογή false. Η αντιγραφή γράφει ΠΟΣΑ - το περσινό ενοίκιο σε έναν
-- μήνα που ο ιδιοκτήτης δεν έχει κοιτάξει ακόμα είναι ένα νούμερο που
-- κανείς δεν επιβεβαίωσε. Ανοίγει όποιος το θέλει, αφού το διαβάσει.
ALTER TABLE shift_templates
  ADD COLUMN IF NOT EXISTS fixed_costs_auto_repeat BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN shift_templates.fixed_costs_auto_repeat IS
  'Τα πάγια του καταστήματος αντιγράφονται μόνα τους από τον προηγούμενο μήνα, όταν ο νέος μήνας ανοίγει άδειος.';

-- Έλεγχος: ποια καταστήματα το έχουν ανοιχτό.
SELECT s.code AS "κωδικός", s.name AS "κατάστημα",
       t.fixed_costs_auto_repeat AS "αυτόματη επανάληψη παγίων"
FROM   shift_templates t
JOIN   stores s ON s.id = t.store_id
ORDER  BY s.code;
