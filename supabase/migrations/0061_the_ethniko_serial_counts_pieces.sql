-- Το Εθνικό: 4 € το κομμάτι, 20 € η πεντάδα.
--
-- Ο αριθμός στο βιβλίο προχωράει ΑΝΑ ΚΟΜΜΑΤΙ. Ο κατάλογος - και ο κώδικας
-- πριν από αυτό - κρατούσε 20 € πάνω σε μία μονάδα, οπότε κάθε βήμα του
-- αριθμού χρέωνε 20 €: πενταπλάσια. 84 -> 80 είναι τέσσερα κομμάτια, 16 €,
-- και χρεωνόταν 80 €.
--
-- Η ετικέτα «πεντάδα» μένει: το κατάστημα το μετράει σε πεντάδες και η
-- στήλη δείχνει 4 x 5 = 20 €. Αυτό που αλλάζει είναι ότι η τιμή κάθεται
-- πλέον πάνω στο κομμάτι, που είναι και η μονάδα που μετράει ο αριθμός.
--
-- Δεν αγγίζει κλεισμένες βάρδιες. Το scratch_lotto_sales είναι αποθηκευμένη
-- στήλη, όχι υπολογισμός, οπότε τα σύνολα που έχουν εγκριθεί μένουν όπως
-- είναι. Αλλάζει μόνο πώς διαβάζεται η γραμμή μέσα στην καρτέλα: οι 12
-- κινήσεις Εθνικού που υπάρχουν έπιαναν 500 € ως πεντάδες, πιάνουν 100 € ως
-- κομμάτια.

UPDATE scratch_catalog
SET    price       = 4,
       bundle_size = 5,
       updated_at  = now()
WHERE  code = 'scr_ethniko_x20'
  AND (price IS DISTINCT FROM 4 OR bundle_size IS DISTINCT FROM 5);

SELECT code,
       name,
       price                     AS "τιμή κομματιού",
       bundle_size               AS "κομμάτια ανά πεντάδα",
       price * bundle_size       AS "τιμή πεντάδας"
FROM   scratch_catalog
WHERE  code = 'scr_ethniko_x20';
