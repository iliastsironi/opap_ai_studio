-- Ένα έξοδο χρεώνεται στο ταμείο όταν το ζητήσει ο χρήστης.
--
-- Ο πράκτορας: «για να μην μπερδευόμαστε, ας βάλει στο έξοδο μία επιλογή να το
-- χρεώνουμε εμείς κατά βούληση· μια επιλογή που να λέει χρέωση στο ταμείο της
-- ημέρας που τρέχει. Αν δεν την πατάμε, να μη χρεώνεται σε κανένα ταμείο, απλά
-- να καταχωρείται στα έξοδα.»
--
-- ΓΙΑΤΙ ΣΤΗΛΗ ΣΤΟ ΙΔΙΟ ΤΟ ΕΞΟΔΟ. Ο υπολογισμός του ταμείου (0044,
-- shift_reconciliation_expenses) αφαιρεί κάθε έξοδο του καταστήματος της ημέρας,
-- ακόμα κι αν δεν έχει δεθεί σε βάρδια («tied to no shift, in which case its own
-- date is all there is»). Το να μην δεθεί λοιπόν ΔΕΝ αρκεί για να μην χρεωθεί.
-- Χρειάζεται ρητό σημάδι πάνω στο έξοδο, και το διαβάζει ο ίδιος ο υπολογισμός.
--
-- Αντικαθιστά τη στήλη expense_categories.paid_from_till (0084), που έκρινε το
-- ίδιο ερώτημα ανά ΚΑΤΗΓΟΡΙΑ και μπέρδευε: το ίδιο έξοδο μετρούσε ή όχι ανάλογα
-- με το πού το έγραφε κανείς. Η στήλη του 0084 μένει στη βάση, αλλά δεν τη
-- διαβάζει πια τίποτα.
--
-- ΤΙ ΑΛΛΑΖΕΙ. Μία στήλη με default ναι, ώστε κάθε υπάρχον έξοδο να συμπεριφέρεται
-- όπως πριν: όποιο μετρούσε, μετράει. Ούτε βάρδια ούτε έξοδο αγγίζει αυτό το
-- migration, και καμία κλεισμένη βάρδια δεν αλλάζει - το αναμενόμενο ταμείο και η
-- απόκλιση μιας βάρδιας αποθηκεύονται στο κλείσιμο και δεν ξαναϋπολογίζονται.

ALTER TABLE shift_expenses
  ADD COLUMN IF NOT EXISTS charged_to_till BOOLEAN NOT NULL DEFAULT TRUE;

