-- Το Εθνικό: μόνο πεντάδες, 20 € η πεντάδα. Ποτέ κομμάτια.
--
-- Αναιρεί την 0061. Ο Owner: «το εθνικό είναι μόνο σε πεντάδες, όχι
-- κομμάτια ποτέ».
--
-- Η 0061 το είχε γυρίσει σε 4 € το κομμάτι x 5. Αυτό δεν υπάρχει ως
-- προϊόν: δεν πωλείται μεμονωμένο λαχνό, άρα δεν υπάρχει τιμή κομματιού να
-- κοστολογηθεί. Ο αριθμός στο βιβλίο προχωράει ανά πεντάδα, κάθε βήμα
-- είναι 20 €, και αυτό ήταν εξαρχής.
--
-- Τα ίδια τα δεδομένα το έλεγαν και δεν ακούστηκαν αρκετά: και οι 12
-- κινήσεις Εθνικού που υπάρχουν ανήκουν σε βάρδιες που έκλεισαν με
-- απόκλιση από -3,08 € έως +6,34 €. Αν κάθε βήμα ήταν 4 € αντί για 20 €, η
-- βάρδια της 29ης Αυγούστου θα έλειπε 66,76 €, όχι 2,76 €. Όταν τα
-- αποθηκευμένα μετρητά συμφωνούν με μια ανάγνωση και διαφωνούν με την
-- άλλη, αυτό είναι απόδειξη, όχι ένδειξη.
--
-- bundle_size μένει NULL: η μονάδα ΕΙΝΑΙ η πεντάδα, οπότε δεν υπάρχει
-- μικρότερη μονάδα να χωριστεί. Ένα bundle_size 5 εδώ θα πολλαπλασίαζε τα
-- 20 € σε 100 €, που είναι το άλλο λάθος που έχει ήδη συμβεί.

UPDATE scratch_catalog
SET    price       = 20,
       bundle_size = NULL,
       updated_at  = now()
WHERE  code = 'scr_ethniko_x20'
  AND (price IS DISTINCT FROM 20 OR bundle_size IS NOT NULL);

SELECT code,
       name,
       price       AS "τιμή πεντάδας",
       bundle_size AS "κομμάτια ανά πεντάδα (πρέπει null)"
FROM   scratch_catalog
WHERE  code = 'scr_ethniko_x20';
