-- Το πρόχειρο δεν ξανανοίγει βάρδια που υποβλήθηκε.
--
-- Ο Owner: «σε μερικές βάρδιες κάνω οριστική υποβολή και δεν την κλείνει·
-- ξαναμπαίνω, την ξανακάνω, και τότε κλείνει».
--
-- Ο οδηγός κλεισίματος αποθηκεύει πρόχειρο με καθυστέρηση 800ms, και το
-- πρόχειρο γράφει ΚΑΙ το status. Η σειρά γίνεται:
--
--   κλικ      →  status = SUBMITTED
--   +800ms    →  πρόχειρο → status = DRAFT_CLOSING
--
-- και η βάρδια ξανανοίγει μόνη της. Τη δεύτερη φορά δεν εκκρεμεί
-- χρονόμετρο, γι' αυτό «δουλεύει» - και γι' αυτό συνέβαινε μόνο σε μερικές.
--
-- Γιατί δεν φάνηκε σε υπαλλήλους: το enforce_shift_immutability (0002)
-- πετάει ήδη 42501 σε όποιον δεν είναι elevated όταν αγγίζει υποβληθείσα
-- βάρδια. Ο κανόνας κάλυπτε τον υπάλληλο και άφηνε έξω ακριβώς αυτόν που
-- δοκιμάζει: τον ιδιοκτήτη.
--
-- Ο client διορθώθηκε και δεν στέλνει πια πρόχειρο μετά την υποβολή, αλλά
-- μένει ένα στενότερο παράθυρο: το πρόχειρο μπορεί να είναι ΗΔΗ στον αέρα
-- όταν πατηθεί η υποβολή. Αυτό δεν κλείνει από τη μεριά του client ποτέ -
-- είναι κούρσα μεταξύ δύο αιτημάτων - οπότε ο κανόνας μπαίνει εδώ, όπου
-- ισχύει για κάθε client και για κάθε ρόλο.
--
-- ΔΙΟΡΘΩΝΕΙ, δεν αρνείται. Η καθυστερημένη αποθήκευση κουβαλάει τα ίδια
-- δεδομένα που μόλις έγραψε η υποβολή· λάθος είναι μόνο ο ισχυρισμός της
-- ότι «αυτό είναι ακόμα πρόχειρο», που ήταν σωστός πριν από μισό
-- δευτερόλεπτο. Μια εξαίρεση θα έδειχνε στον χειριστή «αποτυχία αποθήκευσης»
-- για κάτι εντελώς αβλαβές. Κρατιέται λοιπόν η κατάσταση και περνούν τα
-- υπόλοιπα.
--
-- Το άνοιγμα ξανά είναι άλλος δρόμος και δεν θίγεται: η «Αίτηση Διόρθωσης»
-- γράφει REOPENED ή CORRECTION_REQUESTED, ποτέ DRAFT_CLOSING. Και το
-- πρόχειρο ΠΑΝΩ σε REOPENED επιτρέπεται κανονικά - εκεί η βάρδια όντως
-- ξαναδουλεύεται.

CREATE OR REPLACE FUNCTION shift_draft_never_reopens() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.status IN ('SUBMITTED', 'APPROVED') AND NEW.status = 'DRAFT_CLOSING' THEN
    NEW.status := OLD.status;
    -- Και η ώρα κλεισίματος μένει αυτή της υποβολής. Χωρίς αυτό, ένα
    -- πρόχειρο που δεν κρατάει closed_at θα το μηδένιζε και η βάρδια θα
    -- έδειχνε κλεισμένη χωρίς να ξέρει πότε.
    NEW.closed_at := COALESCE(NEW.closed_at, OLD.closed_at);
    NEW.closed_by_user_id := COALESCE(NEW.closed_by_user_id, OLD.closed_by_user_id);
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_shift_draft_never_reopens ON shifts;

-- BEFORE, και πριν από τα υπόλοιπα κατ' όνομα: η Postgres τρέχει τα
-- same-timing triggers αλφαβητικά, και το «aa_» το βάζει πρώτο ώστε όσα
-- ελέγχουν το NEW.status (π.χ. το κλείδωμα του 0002) να βλέπουν την
-- διορθωμένη τιμή και όχι την ξεπερασμένη.
CREATE TRIGGER aa_trg_shift_draft_never_reopens
  BEFORE UPDATE ON shifts
  FOR EACH ROW EXECUTE FUNCTION shift_draft_never_reopens();

