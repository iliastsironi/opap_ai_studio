-- Το χρηματοκιβώτιο μετριέται σε δεσμίδες.
--
-- Στην καταμέτρηση της βάρδιας υπάρχει τρίτη στήλη, «Χρηματοκιβώτιο», δίπλα στα
-- κέρματα και τα χαρτονομίσματα. Εκεί τα χαρτονομίσματα μετριούνται σε
-- δεσμίδες, όχι ένα-ένα. Πόσα τεμάχια έχει μια δεσμίδα το ορίζει ο admin, ανά
-- κατάστημα (ή για όλο τον οργανισμό), γι' αυτό υπάρχει εδώ και όχι γραμμένο
-- μέσα στον κώδικα.
--
-- Η καταμέτρηση του χρηματοκιβωτίου είναι ΞΕΧΩΡΙΣΤΗ: δεν μπαίνει στο «Σύνολο
-- Μετρητών» ούτε στην απόκλιση της βάρδιας. Γράφεται πάνω στη βάρδια, στο
-- custom_field_values.safe_count, μαζί με τα μεγέθη δεσμίδας που ίσχυαν εκείνη
-- τη στιγμή - μια αλλαγή αύριο δεν αλλάζει τι μετρήθηκε σήμερα.
--
--   safe_count_enabled   Αν φαίνεται η στήλη στο κλείσιμο. Ανοιχτό από προεπιλογή.
--   safe_bundle_sizes    Τεμάχια ανά δεσμίδα, ανά ονομαστική αξία:
--                        5, 10, 20 € = 50 τεμάχια, 50 € = 20, τα υπόλοιπα = 10.
--
-- Ό,τι κλειδί λείπει από το JSON παίρνει την προεπιλογή του στον κώδικα
-- (lib/safeBundles.ts), οπότε ένα μισογραμμένο JSON δεν σπάει το κλείσιμο.

ALTER TABLE shift_templates
  ADD COLUMN IF NOT EXISTS safe_count_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN IF NOT EXISTS safe_bundle_sizes JSONB NOT NULL
    DEFAULT '{"5":50,"10":50,"20":50,"50":20,"100":10,"200":10,"500":10}'::jsonb;

COMMENT ON COLUMN shift_templates.safe_count_enabled IS
  'Φαίνεται η στήλη «Χρηματοκιβώτιο» (δεσμίδες) στην καταμέτρηση του κλεισίματος. Ξεχωριστή καταμέτρηση: δεν μπαίνει στο σύνολο μετρητών ούτε στην απόκλιση.';
COMMENT ON COLUMN shift_templates.safe_bundle_sizes IS
  'Τεμάχια ανά δεσμίδα ανά ονομαστική αξία, π.χ. {"5":50,"50":20,"100":10}.';

