-- Η πάγια παραγγελία του Εθνικού.
--
-- Το 0053 έδωσε πάγια ποσότητα μόνο στο Λαϊκό, γιατί τότε μόνο αυτό ήταν
-- γνωστό ότι έχει. Ο Owner: το Εθνικό έχει κι αυτό πάγια, με δυνατότητα
-- αλλαγής - απλώς δική του, όχι του Λαϊκού.
--
-- Μέχρι τώρα η οθόνη προσυμπλήρωνε κάθε λαχείο με την πάγια του Λαϊκού,
-- που σημαίνει ότι η «Ειδική Έκδοση» και το «Πρωτοχρονιάτικο» - που
-- έρχονται σε άλλη ποσότητα κάθε κλήρωση - άνοιγαν στις 40 πεντάδες του
-- Λαϊκού.
--
-- Πεντάδες, όπως και του Λαϊκού: η μονάδα που παραγγέλνει και μετράει το
-- κατάστημα. NULL = δεν το έχει ορίσει ακόμα, 0 = δεν παίρνει καθόλου.

ALTER TABLE shift_templates
  ADD COLUMN IF NOT EXISTS ethniko_standing_order_bundles integer;

COMMENT ON COLUMN shift_templates.ethniko_standing_order_bundles IS
  'Πάγια παραγγελία Εθνικού σε πεντάδες. NULL = δεν ορίστηκε, 0 = δεν παίρνει.';

SELECT store_id,
       laiko_standing_order_bundles   AS "πάγια Λαϊκού",
       ethniko_standing_order_bundles AS "πάγια Εθνικού"
FROM   shift_templates
ORDER  BY store_id;
