-- Μια κατηγορία εξόδου μπορεί να μένει έξω από το ταμείο της βάρδιας.
--
-- Ο ιδιοκτήτης: «τα πάγια χρεώνονται στο ταμείο, δεν πρέπει να χρεώνονται»,
-- και «ανάλογα το έξοδο να μπορούμε να το αλλάξουμε κατηγορία, αν είναι έξοδα
-- εταιρίας ή πάγιο ή κάτι άλλο».
--
-- ΤΙ ΒΡΕΘΗΚΕ. Το ταμείο μιας βάρδιας αφαιρεί ΚΑΘΕ έξοδο του καταστήματος της
-- ημέρας, ακόμα κι αν δεν έχει δεθεί σε βάρδια (shift_reconciliation_expenses,
-- 0044: «tied to no shift, in which case its own date is all there is»). Δεν
-- ξεχωρίζει το ενοίκιο που πάει με έμβασμα από τη Cosmote που πληρώθηκε από το
-- συρτάρι. Και τα δύο είναι «έξοδα καταστήματος», και τα δύο έπεφταν στο ίδιο
-- ταμείο.
--
-- ΓΙΑΤΙ ΔΙΑΚΟΠΤΗΣ ΑΝΑ ΚΑΤΗΓΟΡΙΑ ΚΑΙ ΟΧΙ ΛΙΣΤΑ «ΠΑΓΙΩΝ». Στα πραγματικά
-- κλεισίματα οι τρεις πληρωμές Cosmote/ΟΤΕ (142,50, 26,90, 158,10 €) βγήκαν όντως
-- από το συρτάρι: το ταμείο που μετρήθηκε ταίριαζε με το αναμενόμενο. Ένας
-- κανόνας «κάθε πάγιο έξω από το ταμείο» θα τα έβγαζε και θα έδειχνε
-- πλεόνασμα. Η απάντηση ανήκει στην κατηγορία που διαλέγει ο ιδιοκτήτης, όχι
-- στο όνομά της.
--
-- ΤΙ ΑΛΛΑΖΕΙ. Μία στήλη, και ένα default που κρατάει όλα όπως ήταν: ναι.
-- Μόνο η δική του κατηγορία «Πάγια Έξοδα» (CUSTOM_PAGIA_EXODA) και όσες
-- είναι πλευράς COMPANY γίνονται «όχι». Τα έξοδα εταιρίας δεν περνούν ούτε
-- τώρα από ταμείο (0075)· η στήλη το λέει κι εκεί, ώστε ένας μόνο κανόνας
-- (countsInTill στο lib/expenseCategories.ts) να απαντάει στην ερώτηση.
--
-- ΔΕΝ ΑΛΛΑΖΕΙ ΤΟ ΠΑΡΕΛΘΟΝ. Το αναμενόμενο ταμείο και η απόκλιση μιας βάρδιας
-- αποθηκεύονται στο κλείσιμο και δεν ξαναϋπολογίζονται· καμία κλεισμένη
-- βάρδια δεν αγγίζεται από αυτό το migration.

ALTER TABLE expense_categories
  ADD COLUMN IF NOT EXISTS paid_from_till BOOLEAN NOT NULL DEFAULT TRUE;

UPDATE expense_categories
   SET paid_from_till = FALSE,
       updated_at = now()
 WHERE (side = 'COMPANY' OR key = 'CUSTOM_PAGIA_EXODA')
   AND paid_from_till IS DISTINCT FROM FALSE;

