/**
 * Πότε το «νέο πακέτο» παύει να δέχεται πληκτρολογημένο κωδικό.
 *
 * Ο κανόνας του Owner: ένα πακέτο μπαίνει στο μαγαζί μόνο μεταφερόμενο από
 * την αποθήκη. Αυτό κλείνει το κενό που ο κώδικας περιγράφει μόνος του -
 * «a mistyped code recorded today is a pack nobody can trace tomorrow».
 *
 * Αλλά η αποθήκη ξεκινά άδεια. Επιβάλλοντάς το από το πρώτο λεπτό, κανένα
 * κατάστημα δεν θα μπορούσε να ανοίξει πακέτο μέχρι να καταχωρηθεί όλο το
 * υπάρχον στοκ - δηλαδή το ταμείο θα σταματούσε απόψε για μια δουλειά που
 * θέλει μέρες. Το να σπάσει το ταμείο για να επιβληθεί η ιχνηλασία είναι
 * χειρότερο από το να λείπει η ιχνηλασία.
 *
 * Οπότε: η αποθήκη αναλαμβάνει μόλις αρχίσει να χρησιμοποιείται. Όσο το
 * κατάστημα δεν έχει κανένα πακέτο καταχωρημένο, το ταμείο δουλεύει όπως
 * πάντα. Από το πρώτο πακέτο και μετά, ο κωδικός έρχεται από εκεί.
 *
 * Ο διακόπτης είναι το ίδιο το απόθεμα, όχι ρύθμιση: μια ρύθμιση θα
 * μπορούσε να ξεχαστεί ανοιχτή για μήνες, ενώ αυτό γυρίζει την ημέρα που
 * μπαίνει το πρώτο πακέτο και δεν ξαναγυρίζει πίσω.
 */

export interface HandoverPack {
  id: string;
  catalog_code: string;
  pack_code: string;
  game_name: string;
  pieces: number;
  unit_price: number;
  received_at: string;
  /** 'IN_WAREHOUSE' ή 'PENDING_DELIVERY' - η μόνη διάκριση που μετράει εδώ. */
  status: string;
}

/** Η θέση από την οποία ανοίγει πακέτο το ταμείο. Μία απάντηση, ένα σημείο. */
export const READY_FOR_TILL = 'PENDING_DELIVERY';

/**
 * Αν ο κωδικός πρέπει να έρθει από την αποθήκη.
 *
 * Το ερώτημα είναι «το κατάστημα ΧΡΗΣΙΜΟΠΟΙΕΙ αποθήκη», όχι «έχει κάτι
 * μέσα αυτή τη στιγμή». Η πρώτη εκδοχή αυτού του κανόνα κοιτούσε το
 * τρέχον απόθεμα και αναβόσβηνε: μόλις βγήκε στο μαγαζί το μοναδικό
 * πακέτο, η αποθήκη άδειασε, ο κανόνας έσβησε και το ταμείο ξαναζήτησε
 * πληκτρολογημένο κωδικό - ακριβώς όταν η ιχνηλασία είχε αρχίσει να
 * δουλεύει.
 *
 * Το κατάστημα που παρέλαβε έστω ένα πακέτο, έστω και περασμένο στο
 * μαγαζί, έχει αποθήκη. Άδειο ράφι σημαίνει «παράγγειλε», όχι «γράψε τον
 * κωδικό στο χέρι».
 *
 * Μόνο για σκρατς. Τα λαχεία δεν έχουν πακέτα 300 € - έχουν παραλαβή ανά
 * κλήρωση, με αριθμό κλήρωσης, και εκείνη τη ροή τη χειρίζεται το
 * lotteryDelivery.ts.
 */
export function warehouseGoverns(usesWarehouse: boolean, isLottery: boolean): boolean {
  return !isLottery && usesWarehouse;
}

/**
 * Τα πακέτα που μπορούν να βγουν για αυτό το παιχνίδι, παλαιότερο πρώτο.
 *
 * Παλαιότερο πρώτο επειδή αυτό θέλει το ράφι: το πακέτο που κάθεται
 * περισσότερο είναι αυτό που πλησιάζει τις 90 ημέρες, και η σειρά της
 * λίστας είναι ο φθηνότερος τρόπος να βγαίνει πρώτο χωρίς να το σκεφτεί
 * κανείς.
 */
export function packsForGame(
  storePacks: ReadonlyArray<HandoverPack> | null | undefined,
  catalogCode: unknown
): HandoverPack[] {
  const code = String(catalogCode ?? '');
  return (storePacks ?? [])
    .filter((p) => p.catalog_code === code)
    .sort((a, b) => String(a.received_at).localeCompare(String(b.received_at)));
}

export interface HandoverChoices {
  /** Παραδομένα: αυτά και μόνο αυτά προσφέρονται για άνοιγμα. */
  ready: HandoverPack[];
  /** Στο ράφι: δεν προσφέρονται, αλλά εξηγούν γιατί η λίστα είναι άδεια. */
  waiting: HandoverPack[];
}

/**
 * Τι μπορεί να ανοίξει το ταμείο για αυτό το παιχνίδι, και τι όχι ακόμα.
 *
 * Ο υπάλληλος κρατάει ΕΝΑ πακέτο στο χέρι. Πριν το 0076 η λίστα του
 * πρόσφερε ό,τι είχε η αποθήκη - στη Λαμία 42 πακέτα - και του ζητούσε να
 * βρει μέσα εκεί αυτό που κρατάει. Τώρα προσφέρεται μόνο ό,τι του
 * παραδόθηκε, που είναι ένα ή δύο.
 *
 * Τα υπόλοιπα δεν πετάγονται: χωρίς αυτά, μια άδεια λίστα θα έλεγε
 * «καταχωρήστε το πρώτα στην αποθήκη» για πακέτο που κάθεται στο ράφι και
 * περιμένει ένα κλικ του αντμιν - και ο υπάλληλος θα πήγαινε να
 * καταχωρήσει δεύτερη φορά κάτι που υπάρχει ήδη.
 */
export function handoverChoices(
  storePacks: ReadonlyArray<HandoverPack> | null | undefined,
  catalogCode: unknown
): HandoverChoices {
  const all = packsForGame(storePacks, catalogCode);
  return {
    ready: all.filter((p) => p.status === READY_FOR_TILL),
    waiting: all.filter((p) => p.status !== READY_FOR_TILL),
  };
}

/**
 * Γιατί δεν μπορεί να ανοίξει πακέτο, ή null αν μπορεί.
 *
 * Τρία διαφορετικά αδιέξοδα, τρία διαφορετικά μηνύματα, γιατί το κάθε ένα
 * θέλει άλλη πράξη από άλλο άνθρωπο:
 *
 *   κανένα πακέτο πουθενά  → καταχώρηση στην αποθήκη, ή παραγγελία στον ΟΠΑΠ
 *   υπάρχει αλλά στο ράφι  → ένα κλικ «Παράδοση» από τον αντμιν
 *   δεν διάλεξε            → ένα κλικ εδώ
 *
 * Ένα κοινό «συμπληρώστε τα πεδία» θα έστελνε τον υπάλληλο να ψάχνει, και
 * το μεσαίο είναι αυτό που θα συναντήσει συχνότερα: το πακέτο υπάρχει, ο
 * αντμιν δεν το έχει παραδώσει ακόμα.
 */
export function handoverProblem(
  ready: ReadonlyArray<HandoverPack>,
  waiting: ReadonlyArray<HandoverPack>,
  selectedId: string | null | undefined
): string | null {
  if (ready.length === 0) {
    if (waiting.length > 0) {
      return waiting.length === 1
        ? 'Υπάρχει ένα πακέτο αυτού του παιχνιδιού στην αποθήκη, αλλά δεν έχει παραδοθεί στο κατάστημα. Ζητήστε παράδοση από την «Αποθήκη Σκρατς».'
        : `Υπάρχουν ${waiting.length} πακέτα αυτού του παιχνιδιού στην αποθήκη, αλλά κανένα δεν έχει παραδοθεί στο κατάστημα. Ζητήστε παράδοση από την «Αποθήκη Σκρατς».`;
    }
    return 'Δεν υπάρχει πακέτο αυτού του παιχνιδιού στην αποθήκη. Καταχωρήστε το πρώτα στην «Αποθήκη Σκρατς».';
  }
  if (!selectedId) return 'Διαλέξτε πακέτο από τα παραδομένα.';
  if (!ready.some((p) => p.id === selectedId)) {
    // Το πακέτο άνοιξε από αλλού όσο ήταν ανοιχτό το παράθυρο.
    return 'Το πακέτο που διαλέξατε δεν είναι πια διαθέσιμο. Ανανεώστε τη λίστα.';
  }
  return null;
}

/**
 * Σε ποια φάση είναι η αποθήκη ΑΥΤΟΥ του καταστήματος.
 *
 * «Φτιάξε μου την αποθήκη για το 498, δεν είναι ενεργοποιημένη.» Δεν υπάρχει
 * διακόπτης να ενεργοποιηθεί - και αυτό είναι επίτηδες (δες το σχόλιο στην
 * κορυφή αυτού του αρχείου): ο διακόπτης είναι το ίδιο το απόθεμα, γιατί μια
 * ρύθμιση ξεχνιέται ανοιχτή για μήνες ενώ το πρώτο καταχωρημένο πακέτο
 * γυρίζει τον κανόνα την ημέρα που πρέπει.
 *
 * Το πρόβλημα ήταν ότι αυτό δεν το έλεγε πουθενά η οθόνη. Ένα κατάστημα με
 * άδεια αποθήκη έδειχνε «Κανένα πακέτο στην αποθήκη», που διαβάζεται ως
 * «κάτι δεν άνοιξε» αντί για «δεν έχει ξεκινήσει ακόμα, και ξεκινά έτσι».
 *
 *   STARTED              έχει καταχωρηθεί έστω ένα πακέτο, ποτέ - το ταμείο
 *                        διαλέγει πια κωδικούς από εδώ.
 *   READY_TO_START       κανένα πακέτο, αλλά υπάρχουν παιχνίδια με 4ψήφιο:
 *                        μια καταχώρηση και ξεκίνησε.
 *   NEEDS_GAME_NUMBERS   κανένα πακέτο ΚΑΙ κανένα παιχνίδι με 4ψήφιο. Εδώ
 *                        δεν φταίει η αποθήκη: χωρίς 4ψήφιο δεν υπάρχει τι
 *                        να σκαναριστεί, και η λίστα παραλαβής είναι άδεια.
 */
export type WarehouseStartState = 'STARTED' | 'READY_TO_START' | 'NEEDS_GAME_NUMBERS';

export function warehouseStartState(input: {
  /** Πακέτα του καταστήματος σε ΟΠΟΙΑΔΗΠΟΤΕ κατάσταση - και τα αποσυρμένα. */
  packCount: number;
  /** Παιχνίδια που μπορούν να παραληφθούν (έχουν 4ψήφιο και μέγεθος). */
  gameCount: number;
}): WarehouseStartState {
  if (input.packCount > 0) return 'STARTED';
  return input.gameCount > 0 ? 'READY_TO_START' : 'NEEDS_GAME_NUMBERS';
}
