/**
 * Είναι αυτή η αλλαγή «άνοιγμα νέου πακέτου», και τίποτα άλλο;
 *
 * Το κουμπί υπήρχε μόνο για τον υπεύθυνο. Στην πράξη το πακέτο το ανοίγει
 * όποιος είναι στον πάγκο όταν τελειώνει το προηγούμενο, και αυτός είναι ο
 * υπάλληλος - τα λόγια του ιδιοκτήτη: «θέλουμε να 'ναι και στους
 * υπαλλήλους».
 *
 * Το άνοιγμα γράφει δύο κλειδωμένα πεδία, το Μπροστά-Αρχικό και το
 * Πίσω-Τελικό, που τα φυλάνε ΤΡΙΑ σημεία: αυτό το κουμπί, ο φύλακας του
 * σώσιμου (lockScratchRowsForSave) και ο trigger της βάσης
 * (trg_enforce_scratch_field_locks, 0006). Αν τα τρία δεν συμφωνούν
 * ακριβώς, το αποτέλεσμα είναι είτε κουμπί που αποτυγχάνει, είτε - χειρότερο
 * - σώσιμο που γυρίζει σιωπηλά τα νούμερα πίσω. Γι' αυτό ο κανόνας ζει εδώ,
 * μία φορά, και ο trigger του 0080 είναι η μετάφρασή του σε SQL.
 *
 * ΓΙΑΤΙ ΕΙΝΑΙ ΑΣΦΑΛΕΣ: η κλειδαριά υπάρχει για να μην μπορεί κανείς να
 * μετακινήσει το σημείο από το οποίο μετριούνται τα λεφτά και να κρύψει
 * πωλήσεις. Το άνοιγμα πακέτου δεν το κάνει αυτό: το openPack χρεώνει
 * ΟΛΟΚΛΗΡΗ την ουρά του παλιού πακέτου ως πουλημένη (tailSoldOnNewPack,
 * από εκεί που βρήκε η βάρδια το πακέτο μέχρι το τέλος του) και κρατάει
 * στιγμιότυπο για αναίρεση. Άρα μπορεί μόνο να ΑΥΞΗΣΕΙ τα οφειλόμενα, ποτέ
 * να τα μειώσει - και με την αποθήκη σε ισχύ ο κωδικός δεν γράφεται καν:
 * διαλέγεται από τα πακέτα που παρέδωσε ο υπεύθυνος.
 *
 * Το ΠΟΙΟ θα είναι το αρχικό νούμερο μένει κλειδωμένο όπως ήταν: το κουτί
 * είναι απενεργοποιημένο για όποιον δεν είναι Owner/Admin και γεμίζει μόνο
 * του με το μηδέν (ή την πάγια ποσότητα, στα λαχεία) - δες το
 * startNoForNewPack παρακάτω, που είναι αυτό το «μόνο του».
 *
 * ΣΧΗΜΑ ΕΔΩ, ΤΙΜΕΣ ΣΤΗ ΒΑΣΗ. Το isPackOpening απαντά «είναι άνοιγμα
 * πακέτου;» και τίποτα άλλο. Τα δύο νούμερα δεν τα πληκτρολογεί ποτέ η
 * οθόνη, οπότε δεν έχει εδώ τι να επικυρωθεί - ένα αίτημα φτιαγμένο στο
 * χέρι όμως δεν περνάει καθόλου από εδώ, και το 0080 άφηνε τη βάση να
 * δεχτεί ό,τι νούμερο της έρθει αρκεί η πράξη να έχει το σωστό σχήμα. Τον
 * έλεγχο των ΤΙΜΩΝ τον κάνει το 0081, στη scratch_pack_opening_allowed():
 * το Μπροστά-Αρχικό είναι μηδέν ή η πάγια ποσότητα, και το Πίσω-Τελικό δεν
 * κατεβαίνει.
 */

import { standingQuantityFor } from './lotteryDelivery.ts';
import { standingOrderPieces } from './laikoCancellation.ts';

const str = (v: unknown): string => String(v ?? '').trim();

export interface PackOpeningRow {
  packCode?: unknown;
  endNo?: unknown;
  backStartNo?: unknown;
  isNewPack?: unknown;
}

/**
 * Το ακριβές σχήμα που αφήνει το openPack πίσω του, και μόνο αυτό:
 *
 *   - ο κωδικός πακέτου ΑΛΛΑΞΕ και δεν είναι κενός (άνοιξε άλλο πακέτο),
 *   - η γραμμή είναι σημειωμένη ως νέο πακέτο,
 *   - δεν έχει μετρηθεί τίποτα πάνω του ακόμα - ούτε μπροστά ούτε πίσω.
 *
 * Μια οποιαδήποτε άλλη αλλαγή στο Μπροστά-Αρχικό πέφτει έξω από εδώ και
 * παραμένει κλειδωμένη, που είναι όλο το νόημα.
 */
export function isPackOpening(
  before: PackOpeningRow | null | undefined,
  after: PackOpeningRow | null | undefined
): boolean {
  if (!after) return false;

  const code = str(after.packCode);
  if (code === '') return false;
  if (code === str(before?.packCode)) return false;

  if (after.isNewPack !== true && str(after.isNewPack) !== 'true') return false;

  if (str(after.endNo) !== '') return false;
  if (str(after.backStartNo) !== '') return false;

  return true;
}

/**
 * Το Μπροστά-Αρχικό που βάζει μόνη της η οθόνη όταν ανοίγει νέο πακέτο.
 *
 * Ένα καινούριο πακέτο ξεκινά από το μηδέν. Μία εξαίρεση: τα δύο λαχεία με
 * πάγια ποσότητα, όπου το «αρχικό» δεν είναι θέση μέσα σε πακέτο αλλά το
 * απόθεμα που παραδόθηκε - Λαϊκό, 40 πεντάδες στη Λαμία, 200 κομμάτια.
 *
 * Ήταν δύο γραμμές μέσα στο onClick του κουμπιού. Βγαίνουν εδώ γιατί από
 * το 0081 η βάση δέχεται ΜΟΝΟ αυτές τις τιμές από υπάλληλο: αν η οθόνη
 * αρχίσει να προσυμπληρώνει κάτι άλλο και η βάση δεν το μάθει, το άνοιγμα
 * θα σηκώνει 42501 πάνω στον πάγκο. Μία απάντηση, ένα σημείο, και ένα τεστ
 * που σπάει πρώτο.
 */
export function startNoForNewPack(
  row: { id?: unknown; bundleSize?: unknown } | null | undefined,
  standingOrders?: Record<string, unknown> | null
): string {
  const standing = standingQuantityFor(row?.id, standingOrders);
  return standing === null ? '0' : String(standingOrderPieces(standing, row?.bundleSize));
}
