/**
 * Ο πάροχος: αυτός που δίνει την εφαρμογή, όχι ο πελάτης που τη χρησιμοποιεί.
 *
 * Ο ιδιοκτήτης: «οι καταγραφές ελέγχου δεν έχει νόημα να υπάρχουν στους χρήστες
 * και να εμφανίζονται· να υπάρχουν για όλους, αλλά εγώ σαν πάροχος να έχω
 * access, σαν support».
 *
 * Οι καταγραφές γράφονται για όλους, όπως πάντα (τα triggers της βάσης δεν
 * άλλαξαν). Διαβάζονται όμως μόνο από τον ρόλο PLATFORM_ADMIN, που δεν
 * προσφέρεται σε καμία οθόνη και δίνεται μόνο απευθείας στη βάση. Ο ιδιοκτήτης
 * του πελάτη (ORG_OWNER) δεν τον έχει, ακόμα κι αν το '*' του δίνει όλα τα
 * υπόλοιπα δικαιώματα.
 *
 * Η οθόνη κρύβει την καρτέλα· την πραγματική πύλη την κρατάει η πολιτική
 * audit_logs_select (0092). Σε φύλλο χωρίς εισαγωγές, ώστε να τη διαβάζουν και
 * το μενού και το App χωρίς κύκλο.
 */

/** Ο ρόλος του παρόχου, όπως είναι γραμμένος στη βάση (users.role_code). */
export const PROVIDER_ROLE = 'PLATFORM_ADMIN';

/** Οι καρτέλες που ανοίγουν μόνο για τον πάροχο. */
export const PROVIDER_ONLY_TABS: ReadonlyArray<string> = ['audit'];

export function isProvider(roleCodes: ReadonlyArray<string> | null | undefined): boolean {
  return (roleCodes ?? []).some((code) => code === PROVIDER_ROLE);
}
