/**
 * Η απόκλιση που ανήκει σε ΑΥΤΗ τη βάρδια.
 *
 * Το `discrepancy` μιας βάρδιας είναι σωρευτικό της ημέρας, γιατί σωρευτικά
 * είναι και τα δύο που το φτιάχνουν: το μετρημένο και το αναμενόμενο
 * μετράνε από το άνοιγμα της ΗΜΕΡΑΣ, όχι της βάρδιας. Στα πραγματικά
 * δεδομένα φαίνεται καθαρά - στις 7/10 η πρωινή μέτρησε 2.352 και η
 * μεσημεριανή 5.380 στο ίδιο ταμείο.
 *
 * Άρα η δεύτερη βάρδια κουβαλάει μέσα της το μείον της πρώτης. Στις 11/10 η
 * πρωινή βγήκε −2,16 και η μεσημεριανή +0,24: η δική της ήταν +2,40, και
 * πλήρωνε το μείον του προηγούμενου μέσα στο δικό της νούμερο. Αυτό είναι
 * το «το μείον συνεχίζει στο επόμενο ταμείο» που ανέφερε ο Owner.
 *
 * Ίδιο σχήμα με το scratch_day_baseline, που έλυσε ακριβώς το ίδιο
 * πρόβλημα για τα σκρατς: κρατάς τι είχε η ημέρα όταν άνοιξες, και το
 * αφαιρείς.
 *
 *   δική της = σωρευτική τώρα − σωρευτική όταν άνοιξε
 *
 * Το άθροισμα των «δικών τους» μιας ημέρας ισούται με τη σωρευτική της
 * τελευταίας βάρδιας, οπότε καμία αναφορά δεν χάνει ευρώ.
 */

const num = (v: unknown): number => {
  const n = Number(v);
  return Number.isFinite(n) ? n : 0;
};

const round2 = (n: number): number => Math.round(n * 100) / 100 + 0;

/**
 * Πόσο από τη σωρευτική απόκλιση ανήκει σε αυτή τη βάρδια.
 *
 * Η πρώτη της ημέρας έχει βάση μηδέν, οπότε η σωρευτική ΕΙΝΑΙ η δική της.
 */
export function ownDiscrepancy(cumulative: unknown, baseline: unknown): number {
  return round2(num(cumulative) - num(baseline));
}

/**
 * Η ανοχή που ισχύει για αυτή τη βάρδια.
 *
 * Πλήρης σε κάθε βάρδια, όχι μοιρασμένη στη μέρα - απόφαση του Owner. Ο
 * λόγος στέκει: η ανοχή υπάρχει επειδή ένας άνθρωπος που μετράει μετρητά
 * κάνει λάθη των λίγων λεπτών, και δύο άνθρωποι κάνουν δύο τέτοια λάθη. Το
 * να μοιραστεί θα σήμαινε ότι ο δεύτερος της ημέρας έχει λιγότερο περιθώριο
 * για την ίδια δουλειά.
 */
export function toleranceFor(threshold: unknown): number {
  return Math.max(0, round2(num(threshold)));
}

export interface ShiftSettlement {
  /** Η απόκλιση αυτής της βάρδιας, με πρόσημο. */
  own: number;
  /** Όσο απορροφά το ταμείο - αρνητικό για έλλειμμα, θετικό για πλεόνασμα. */
  absorbed: number;
  /** Όσο χρεώνεται ο υπάλληλος. Πάντα θετικό ή μηδέν. */
  charged: number;
}

/**
 * Πώς τακτοποιείται η απόκλιση μιας βάρδιας.
 *
 * Δίδυμο του discrepancy_absorbed / discrepancy_charge της βάσης (0034),
 * εφαρμοσμένο όμως στη ΔΙΚΗ ΤΗΣ απόκλιση και όχι στη σωρευτική - που είναι
 * όλη η αλλαγή. Ένα πλεόνασμα απορροφάται ολόκληρο· ένα έλλειμμα
 * απορροφάται ως την ανοχή και το υπόλοιπο χρεώνεται.
 */
export function settleShift(cumulative: unknown, baseline: unknown, threshold: unknown): ShiftSettlement {
  const own = ownDiscrepancy(cumulative, baseline);
  const limit = toleranceFor(threshold);

  if (own >= 0) return { own, absorbed: own, charged: 0 };

  const shortage = -own;
  const absorbed = -Math.min(shortage, limit);
  return { own, absorbed: round2(absorbed), charged: round2(Math.max(0, shortage - limit)) };
}
